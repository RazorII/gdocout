"""Shared test helpers: tiny valid Office files, stub files, and a fake Google.

The fake Google answers the way the real one was measured to (2026-10-24):
200 + file, 401 + view page 200 for "download turned off", 401 + 401 for a
private file, 404 for a missing one, plus throttling and flaky answers.
"""

from __future__ import annotations

import io
import json
import threading
import zipfile
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

import pytest

W = "http://schemas.openxmlformats.org/wordprocessingml/2006/main"
S = "http://schemas.openxmlformats.org/spreadsheetml/2006/main"
P = "http://schemas.openxmlformats.org/presentationml/2006/main"
CT = '<?xml version="1.0"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"/>'


def _zip(parts: dict) -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for name, data in parts.items():
            z.writestr(name, data)
    return buf.getvalue()


def make_docx(text: str = "Hello there world") -> bytes:
    body = f'<w:document xmlns:w="{W}"><w:body><w:p><w:r><w:t>{text}</w:t></w:r></w:p></w:body></w:document>'
    return _zip({"[Content_Types].xml": CT, "word/document.xml": body})


def make_xlsx(sheets=("One", "Two", "Three")) -> bytes:
    s = "".join(f'<sheet name="{n}" sheetId="{i}"/>' for i, n in enumerate(sheets, 1))
    return _zip({"[Content_Types].xml": CT, "xl/workbook.xml": f'<workbook xmlns="{S}"><sheets>{s}</sheets></workbook>'})


def make_pptx(slides: int = 2) -> bytes:
    ids = "".join(f'<p:sldId id="{256 + i}"/>' for i in range(slides))
    return _zip({"[Content_Types].xml": CT, "ppt/presentation.xml": f'<p:presentation xmlns:p="{P}"><p:sldIdLst>{ids}</p:sldIdLst></p:presentation>'})


def make_kmz() -> bytes:
    kml = '<kml xmlns="http://www.opengis.net/kml/2.2"><Document><Placemark/><Placemark/></Document></kml>'
    return _zip({"doc.kml": kml})


def stub(path: Path, file_id: str, key: str = "") -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps({"": "WARNING! DO NOT EDIT THIS FILE!", "doc_id": file_id, "resource_key": key, "email": "x@example.com"}))
    return path


HTML_LOGIN = b"<!DOCTYPE html><html><head><title>Sign in - Google Accounts</title></head><body>login</body></html>"
HTML_404 = b"<!DOCTYPE html><html><head><title>Page Not Found</title></head><body>gone</body></html>"


class FakeGoogle:
    """IDs are named for how they behave: okdoc..., dloff..., private..., gone..., busy..., flaky..., forbid..., webpage..."""

    def __init__(self):
        self.hits = []
        self.busy_left = {}
        self.flaky_left = {}
        self.lock = threading.Lock()
        self.always_429 = False
        self.throttle_next = 0

    def answer(self, path: str):
        with self.lock:
            self.hits.append(path)
        parts = [p for p in path.split("?")[0].split("/") if p]
        # /docs/<kind>/d/<id>/<action...>  or  /maps/d/kml
        if parts[:3] == ["maps", "d", "kml"]:
            return 200, "application/vnd.google-earth.kmz", make_kmz()
        kind, file_id, action = parts[1], parts[3], parts[4]
        if self.always_429:
            return 429, "text/html", b"<html><title>Too Many Requests</title></html>"
        with self.lock:
            if self.throttle_next > 0:
                self.throttle_next -= 1
                return 429, "text/html", b"<html><title>Too Many Requests</title></html>"
        view = action in ("edit", "view")
        if file_id.startswith("busy"):
            with self.lock:
                left = self.busy_left.setdefault(file_id, 2)
                if left > 0:
                    self.busy_left[file_id] = left - 1
                    return 429, "text/html", b"<html><title>Too Many Requests</title></html>"
        if file_id.startswith("flaky"):
            with self.lock:
                left = self.flaky_left.setdefault(file_id, 1)
                if left > 0:
                    self.flaky_left[file_id] = left - 1
                    return 500, "text/html", b"<html><title>Error</title></html>"
        if file_id.startswith("gone"):
            return 404, "text/html", HTML_404
        if file_id.startswith("private"):
            return 401, "text/html", HTML_LOGIN
        if file_id.startswith("dloff"):
            return (200, "text/html", b"<html><title>Doc</title></html>") if view else (401, "text/html", HTML_LOGIN)
        if file_id.startswith("forbid"):
            return 403, "text/html", b"<html><title>Download quota exceeded</title></html>"
        if file_id.startswith("webpage"):
            return 200, "text/html", b"<!DOCTYPE html><html><head><title>Something odd</title></head></html>"
        if view:
            return 200, "text/html", b"<html><title>Doc</title></html>"
        if kind == "document":
            return 200, "application/vnd.openxmlformats-officedocument.wordprocessingml.document", make_docx()
        if kind == "spreadsheets":
            return 200, "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet", make_xlsx()
        if kind == "presentation":
            return 200, "application/vnd.openxmlformats-officedocument.presentationml.presentation", make_pptx()
        return 404, "text/html", HTML_404


@pytest.fixture
def fake_google():
    fake = FakeGoogle()

    class Handler(BaseHTTPRequestHandler):
        def do_GET(self):
            code, ctype, body = fake.answer(self.path)
            self.send_response(code)
            self.send_header("Content-Type", ctype)
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)

        def log_message(self, *a):
            pass

    server = ThreadingHTTPServer(("127.0.0.1", 0), Handler)
    t = threading.Thread(target=server.serve_forever, daemon=True)
    t.start()
    base = f"http://127.0.0.1:{server.server_address[1]}"
    fake.rewrite = lambda u: u.replace("https://docs.google.com", base + "/docs").replace("https://www.google.com/maps", base + "/maps")
    yield fake
    server.shutdown()
